/**
 * FILE: fieldStyles.ts
 * DESCRIPTION: The shared look of a form control, and the type FormField hands
 *              to whatever it wraps.
 *
 *              WHY THIS IS A .ts FILE AND NOT PART OF FormField.tsx: the
 *              `react-refresh/only-export-components` lint rule. A .tsx file
 *              that exports anything other than components breaks Fast
 *              Refresh's ability to hot-swap that module, so React has to do a
 *              full reload instead of preserving state. Helpers and types
 *              therefore live in plain .ts files beside the component.
 *
 *              The class string lives in one place so a text field, a textarea
 *              and a date field cannot drift apart visually. These are the
 *              exact classes the old TextField used, so nothing in the app
 *              should look any different after this change.
 *
 * LAST UPDATED: 2026-10-16 - File Created (Josh Iehle)
 */

// -------------------- Types --------------------

/**
 * What FormField hands to the control it wraps.
 *
 * All three exist because accessibility attributes have to sit on the CONTROL,
 * while the ids they point at are generated by the wrapper.
 */
export interface FieldRenderProps {
  /** Put this on the control. The <label> already points at it. */
  id: string;
  /**
   * Put this on the control as `aria-describedby`. Undefined when there is no
   * hint and no error, which is the correct value for the attribute - an empty
   * string would announce nothing but still be present.
   */
  describedBy: string | undefined;
  /** Put this on the control as `aria-invalid`. */
  invalid: boolean;
}

// -------------------- Control Styling --------------------

/**
 * The input / textarea / select class string.
 *
 * Takes `invalid` so an errored field gets a red border without every caller
 * repeating the conditional. Note there is no `mt-1` here - the spacing
 * between label and control belongs to FormField's layout, not to the control.
 */
export function controlClasses(invalid: boolean): string {
  return [
    'w-full rounded-md border-2 bg-ink-100 px-3 py-2 text-ink-900',
    'duration-150 focus:border-brand-500',
    invalid ? 'border-red-400' : 'border-ink-300',
    'disabled:opacity-50',
  ].join(' ');
}
